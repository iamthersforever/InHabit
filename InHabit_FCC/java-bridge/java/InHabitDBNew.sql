-- 1. Which students reside in Alpha Block, Room 101?
select user.FirstName, user.LastName, student.PRN, student.BlockName, student.FloorNumber, student.Wing
from user
inner join student on user.UserID = student.UserID
where student.BlockName = "Alpha"
and student.Wing = "101";

-- 2. Find all complaints which are currently 'Open' or 'In Progress'
select *
from complaint
where Status = "Open" or Status = "In Progress";

-- 3. Display complaints along with the student name who filed them
select complaint.TicketID, complaint.Title, complaint.Category, complaint.Status, user.FirstName, user.LastName
from complaint
inner join student on complaint.FiledBy = student.UserID
inner join user on student.UserID = user.UserID;

-- 4. Find technicians along with their supervising warden details
select u_tech.FirstName as TechName, technician.Trade, u_ward.FirstName as WardenName, warden.BlockInCharge
from technician
inner join user u_tech on technician.UserID = u_tech.UserID
inner join warden on technician.SupervisorID = warden.UserID
inner join user u_ward on warden.UserID = u_ward.UserID;

-- 5. Group By, Having & Order By: Give category-wise complaint count
select Category, count(TicketID) as TotalComplaints
from complaint
group by Category
order by TotalComplaints desc;

