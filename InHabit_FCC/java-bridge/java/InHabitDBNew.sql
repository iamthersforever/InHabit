DROP DATABASE IF EXISTS InHabitDBNew;
CREATE DATABASE InHabitDBNew;
USE InHabitDBNew;

-- Table 01: USER
CREATE TABLE USER(
 USERID VARCHAR(30) PRIMARY KEY,
 FIRSTNAME VARCHAR(50) not null,
 MIDDLENAME VARCHAR(50) null,
 LASTNAME VARCHAR(50) null,
 INSTITUTIONALEMAIL VARCHAR(100) unique not null,
 PASSWORDHASH VARCHAR(100) not null,
 ROLE VARCHAR(30) not null
);

-- Table 02: USER_PHONE
CREATE TABLE USER_PHONE(
 PHONEID INT PRIMARY KEY,
 USERID VARCHAR(30), FOREIGN KEY(USERID) references USER(USERID) on delete cascade,
 PHONENUMBER VARCHAR(20) not null
);

-- Table 03: STUDENT
CREATE TABLE STUDENT(
 USERID VARCHAR(30) PRIMARY KEY,
 PRN VARCHAR(20) unique not null,
 BLOCKNAME VARCHAR(30) not null,
 FLOORNUMBER INT not null,
 WING VARCHAR(20) not null,
 FOREIGN KEY(USERID) references USER(USERID) on delete cascade
);

-- Table 04: STAFF
CREATE TABLE STAFF(
 USERID VARCHAR(30) PRIMARY KEY,
 STAFFID VARCHAR(20) unique not null,
 DEPARTMENT VARCHAR(50) not null,
 FOREIGN KEY(USERID) references USER(USERID) on delete cascade
);

-- Table 05: ADMIN
CREATE TABLE ADMIN(
 USERID VARCHAR(30) PRIMARY KEY,
 ACCESSLEVEL VARCHAR(30) not null,
 FOREIGN KEY(USERID) references STAFF(USERID) on delete cascade
);

-- Table 06: WARDEN
CREATE TABLE WARDEN(
 USERID VARCHAR(30) PRIMARY KEY,
 BLOCKINCHARGE VARCHAR(50) not null,
 FOREIGN KEY(USERID) references STAFF(USERID) on delete cascade
);

-- Table 07: TECHNICIAN
CREATE TABLE TECHNICIAN(
 USERID VARCHAR(30) PRIMARY KEY,
 TRADE VARCHAR(50) not null,
 SUPERVISORID VARCHAR(30) null,
 FOREIGN KEY(USERID) references STAFF(USERID) on delete cascade,
 FOREIGN KEY(SUPERVISORID) references WARDEN(USERID) on delete set null
);

-- Table 08: COMPLAINT
CREATE TABLE COMPLAINT(
 TICKETID INT PRIMARY KEY,
 TITLE VARCHAR(150) not null,
 DESCRIPTION TEXT not null,
 CATEGORY VARCHAR(50) not null,
 STATUS VARCHAR(30) default 'Open',
 CREATEDAT DATETIME not null,
 WARDENCONFIRMED BOOLEAN default false,
 STUDENTCONFIRMED BOOLEAN default false,
 FILEDBY VARCHAR(30), FOREIGN KEY(FILEDBY) references STUDENT(USERID) on delete cascade
);

-- Table 09: ESCALATED_COMPLAINT
CREATE TABLE ESCALATED_COMPLAINT(
 TICKETID INT PRIMARY KEY,
 ESCALATEDAT DATETIME not null,
 FOREIGN KEY(TICKETID) references COMPLAINT(TICKETID) on delete cascade
);

-- Table 10: SENSITIVE_COMPLAINT
CREATE TABLE SENSITIVE_COMPLAINT(
 TICKETID INT PRIMARY KEY,
 ISANONYMOUS BOOLEAN default true,
 FOREIGN KEY(TICKETID) references COMPLAINT(TICKETID) on delete cascade
);

-- Table 11: ATTACHMENT
CREATE TABLE ATTACHMENT(
 ATTACHMENTID VARCHAR(20) PRIMARY KEY,
 TICKETID INT, FOREIGN KEY(TICKETID) references COMPLAINT(TICKETID) on delete cascade,
 FILEURL VARCHAR(255) not null,
 FILETYPE VARCHAR(50) not null,
 FILESIZE_MB DECIMAL(5,2) not null,
 UPLOADEDAT DATETIME not null
);

-- Table 12: VOTE
CREATE TABLE VOTE(
 VOTEID VARCHAR(20) PRIMARY KEY,
 TICKETID INT, FOREIGN KEY(TICKETID) references COMPLAINT(TICKETID) on delete cascade,
 USERID VARCHAR(30), FOREIGN KEY(USERID) references STUDENT(USERID) on delete cascade,
 VOTETYPE VARCHAR(20) default 'Upvote',
 VOTEDAT DATETIME not null,
 UNIQUE(TICKETID, USERID)
);

-- Table 13: STATUS_AUDIT_LOG
CREATE TABLE STATUS_AUDIT_LOG(
 LOGID INT PRIMARY KEY,
 TICKETID INT, FOREIGN KEY(TICKETID) references COMPLAINT(TICKETID) on delete cascade,
 CHANGEDBY VARCHAR(30) null, FOREIGN KEY(CHANGEDBY) references USER(USERID) on delete set null,
 OLDSTATUS VARCHAR(30) not null,
 NEWSTATUS VARCHAR(30) not null,
 CHANGEDAT DATETIME not null
);

-- Table 14: TICKET_ASSIGNMENT
CREATE TABLE TICKET_ASSIGNMENT(
 ASSIGNMENTID VARCHAR(20) PRIMARY KEY,
 TICKETID INT, FOREIGN KEY(TICKETID) references COMPLAINT(TICKETID) on delete cascade,
 WARDENID VARCHAR(30) null, FOREIGN KEY(WARDENID) references WARDEN(USERID) on delete set null,
 TECHNICIANID VARCHAR(30) null, FOREIGN KEY(TECHNICIANID) references TECHNICIAN(USERID) on delete set null,
 ASSIGNEDAT DATETIME not null,
 RESOLUTIONNOTES TEXT null
);

-- Table 15: LOST_AND_FOUND
CREATE TABLE LOST_AND_FOUND(
 ITEMID VARCHAR(20) PRIMARY KEY,
 ITEMNAME VARCHAR(100) not null,
 DESCRIPTION TEXT not null,
 LOCATIONFOUND VARCHAR(100) not null,
 ITEMTYPE VARCHAR(20) not null,
 STATUS VARCHAR(20) default 'Open',
 REPORTEDAT DATETIME not null,
 REPORTEDBY VARCHAR(30) null, FOREIGN KEY(REPORTEDBY) references USER(USERID) on delete set null
);

