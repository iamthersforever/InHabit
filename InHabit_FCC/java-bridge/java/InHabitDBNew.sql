-- 9. Stored Function: Calculate Days Pending for a given TicketID
DELIMITER $$
CREATE FUNCTION fn_DaysPending(p_ticket_id INT)
RETURNS INT
DETERMINISTIC
BEGIN
    DECLARE v_days INT;
    SELECT DATEDIFF(CURRENT_DATE(), DATE(CreatedAt)) INTO v_days
    FROM COMPLAINT
    WHERE TicketID = p_ticket_id;
    RETURN IFNULL(v_days, 0);
END$$
DELIMITER ;

